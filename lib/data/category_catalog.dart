/// Single hardcoded source for the category shopping flow.
///
/// Every product declares where it belongs via [_CatalogProduct.placements]
/// (categoryId -> subcategoryId), so the Category screen, the Subcategory
/// screen and their filters all read the same mapping. A product can live in
/// more than one category (e.g. sneakers under Fashion > Footwear and under
