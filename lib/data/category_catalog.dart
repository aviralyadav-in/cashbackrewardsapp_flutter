  static const Map<String, String> _subcategoryAliases = {
    'skincare': 'skincare',
    'fragrance': 'fragrances',
    'personalcare': 'wellness',
    'womensbags': 'bags',
    'handbags': 'bags',
    'kitchenaccessories': 'kitchen',
    'homedecor': 'home_decor',
    'eyewear': 'sunglasses',
  };

  /// Canonical category id for any id/alias used across the app.
  static String canonicalCategoryId(String raw) {
    final key = _norm(raw);
    return _categoryAliases[key] ?? key;
  }

  /// Canonical subcategory id, or null for "all" / empty.
  static String? canonicalSubcategoryId(String? raw) {
    if (raw == null) return null;
    final loose = _loose(raw);
    if (loose.isEmpty || loose == 'all') return null;
    return _subcategoryAliases[loose] ?? _norm(raw);
  }

  static bool hasCategory(String raw) =>
      _definitions.containsKey(canonicalCategoryId(raw));

  static CategoryDefinition? definitionFor(String raw) =>
      _definitions[canonicalCategoryId(raw)];

  /// Products for a category, optionally narrowed to one subcategory.
  /// A gender subcategory ('men' / 'women') matches on product gender.
  static List<CategoryDealModel> productsFor(
    String categoryId, {
    String? subcategoryId,
  }) {
    final cat = canonicalCategoryId(categoryId);
    final sub = canonicalSubcategoryId(subcategoryId);

    return _products
        .where((p) => p.placements.containsKey(cat))
        .where((p) {
          if (sub == null) return true;
          final placed = _loose(p.placements[cat]!);
          final gender = _loose(p.gender ?? '');
          return placed == _loose(sub) || gender == _loose(sub);
        })
        .map((p) => p.toDeal(cat))
        .toList();
  }

  /// Display name for a subcategory of [categoryId], if known.
  static String? subcategoryName(String categoryId, String? subcategoryId) {
    final sub = canonicalSubcategoryId(subcategoryId);
    if (sub == null) return null;
    final def = definitionFor(categoryId);
    for (final s in def?.subcategories ?? const <SubcategoryItemModel>[]) {
      if (_loose(s.id) == _loose(sub)) return s.name;
    }
    return null;
  }

