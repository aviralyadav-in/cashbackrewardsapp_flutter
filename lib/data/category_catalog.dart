  final CategoryOverviewModel overview;
  final List<SubcategoryItemModel> subcategories;
  final List<CategoryStoreModel> popularStores;

  const CategoryDefinition({
    required this.overview,
    required this.subcategories,
    required this.popularStores,
  });
}

class _CatalogProduct {
  final String id;
  final String title;
  final String brand;
  final String store;
  final String imageUrl;
  final double originalPrice;
  final double discountedPrice;
  final String couponCode;
  final double couponDiscount;
  final String badge;
  final List<String> storesAvailable;
  final bool isBestDeal;
  final String? gender;
  final String? style;
  final String? productType;

  /// categoryId -> subcategoryId
  final Map<String, String> placements;

  const _CatalogProduct({
    required this.id,
    required this.title,
    required this.brand,
    required this.store,
    required this.imageUrl,
    required this.originalPrice,
    required this.discountedPrice,
    required this.couponCode,
    required this.couponDiscount,
    required this.badge,
    required this.storesAvailable,
    required this.placements,
    this.isBestDeal = true,
    this.gender,
    this.style,
    this.productType,
  });

  /// Brand offer = the store's own price cut (original vs selling price).
  double get _brandDiscountPercentage => originalPrice > 0
      ? ((originalPrice - discountedPrice) / originalPrice * 100).roundToDouble()
      : 0;

  CategoryDealModel toDeal(String categoryId) {
    return CategoryDealModel(
      id: id,
      title: title,
      brand: brand,
      store: store,
      imageUrl: imageUrl,
      originalPrice: originalPrice,
      discountedPrice: discountedPrice,
      discountPercentage: _brandDiscountPercentage,
      cashbackPercentage: 0,
      cashbackAmount: 0,
      couponCode: couponCode,
      couponDiscount: couponDiscount,
      effectiveSavings: 0,
      effectivePrice: discountedPrice,
      isBestDeal: isBestDeal,
      badge: badge,
      storesAvailable: storesAvailable,
      gender: gender,
      style: style,
      subcategoryId: placements[categoryId],
      productType: productType,
    ).withAppCashback();
  }
}
